"""Build Modern Greek lemma bank with Hebrew glosses."""
import re
BANK = []
seen = set()

def add(lem, he, pos, theme, cefr):
    lem = lem.strip()
    k = lem.lower()
    if not k or k in seen: return
    if re.search(r"[A-Za-zА-Яа-яЁё]", lem): return
    if not re.search(r"[Α-Ωα-ωάέήίόύώΆΈΉΊΌΎΏϊΐϋΰ]", lem): return
    seen.add(k)
    BANK.append((lem, he, pos, theme, cefr))

def bulk(rows, theme, cefr, pos=None):
    for r in rows:
        if len(r) == 2:
            w,h = r; p = pos or "n"
        elif len(r) == 3:
            w,h,p = r
        else:
            w,h,p,c = r; add(w,h,p,theme,c); continue
        add(w,h,p,theme,cefr)

