def expand_level(level_id, title_he, subtitle_he, tracker, min_lessons):
    units = []
    if level_id == "A1":
        units.append(alphabet_unit(tracker))
        seeds = seeds_a1()
        cefr = ("a1","a2")
    else:
        seeds = seeds_level(level_id)
        cefr = {"A2":("a1","a2"),"B1":("a2","b1"),"B2":("b1","b2"),"C1":("b1","b2","c1"),"C2":("b2","c1","c2")}[level_id]

    for uid, the, tru, curated, tip, target in seeds:
        rows = curated_plus_vocab(tracker, curated, cefr, None, target)
        units.append(build_unit(level_id, uid, the, tru, rows, tip=tip))

    def count_lessons(us):
        return sum(len(u["lessons"]) for u in us)

    extra_i = 1
    max_extra = {"A1": 50, "A2": 55, "B1": 95, "B2": 120, "C1": 110, "C2": 100}.get(level_id, 50)
    while extra_i <= max_extra:
        below_min = count_lessons(units) < min_lessons
        unused = tracker.pick(80, cefr=cefr)
        if len(unused) < 12:
            unused = tracker.sample_band(80, cefr=cefr) or tracker.sample_band(80)
        if not below_min:
            band_unused = [x for x in tracker.bank if x["cefr"] in cefr and x["lemma"].lower() not in tracker.introduced]
            if len(band_unused) < 20:
                break
            unused = band_unused[:80]
        if len(unused) < 6:
            break
        rows = []
        start = (extra_i * 17) % max(1, len(unused))
        ordered = unused[start:] + unused[:start]
        for u in ordered:
            for ru, he in natural_rows_for_lemma(u):
                rows.append((ru, he))
                tracker.mark_text(ru)
            tracker.mark_text(u["lemma"])
        uid = f"{level_id.lower()}-u{90+extra_i:02d}"
        tip = "מילים חדשות מהמאגר — ניסוח טבעי" if below_min else "חזרה מגוונת על אוצר המילים"
        units.append(build_unit(level_id, uid, f"אוצר מילים {extra_i}", f"Λεξιλόγιο {extra_i}", rows[:56], tip=tip))
        extra_i += 1

    return {"id": level_id, "titleHe": title_he, "subtitleHe": subtitle_he, "units": units}

def write_level(obj, split_at=None):
    lid = obj["id"]
    low = lid.lower()
    units = obj["units"]
    path = os.path.join(OUT, f"{low}.js")
    write_level_js(path, lid, obj["titleHe"], obj["subtitleHe"], units)
    size = os.path.getsize(path)
    if size > 450_000:
        mid = len(units)//2
        p1 = os.path.join(OUT, f"{low}-part1.js")
        p2 = os.path.join(OUT, f"{low}-part2.js")
        write_level_js(p1, lid, obj["titleHe"], obj["subtitleHe"], units[:mid])
        raw = json.dumps(units[mid:], ensure_ascii=False, separators=(",", ":"))
        with open(p2, "w", encoding="utf-8") as f:
            f.write(f"/* Auto-generated {lid} part2 */\n")
            f.write(f"(function(){{var L=window.RL_LEVEL_{lid};if(!L)return;L.units=L.units.concat({raw});}})();\n")
        os.remove(path)
        return [f"{low}-part1.js", f"{low}-part2.js"], size
    return [f"{low}.js"], size

